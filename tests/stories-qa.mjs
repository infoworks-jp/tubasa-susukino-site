import assert from 'node:assert/strict';
import { buildStories, facebookCopy } from '../scripts/stories.mjs';
const now = new Date('2026-10-24T00:00:00Z');
const item = {slug:'qa-only',title:'検証用 <title>',paragraphs:['検証用 <script>alert(1)</script>','改行\nを保持'],publishedAt:'2026-10-20T18:00:00+09:00',approved:true};
const data = {seriesTitle:'検証専用',episodes:[item]};
assert.equal(buildStories({seriesTitle:null,episodes:[]},now).size,0);
const pages = buildStories(data,now);
assert.equal(pages.size,2);
assert(pages.get('stories/index.html').includes('/stories/qa-only/'));
const html = pages.get('stories/qa-only/index.html');
assert(html.includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
assert(!html.includes('<script>'));
assert(html.includes('index, follow'));
assert(!html.includes('noindex'));
assert.equal(facebookCopy(data.seriesTitle,item).split('\n\n').slice(2).join('\n\n'),item.paragraphs.join('\n\n'));
for (const changed of [{approved:false},{slug:'../escape'},{publishedAt:'2027-01-01T18:00:00+09:00'},{publishedAt:'2026-02-30T18:00:00+09:00'},{publishedAt:'bad'},{paragraphs:[]}]) assert.throws(() => buildStories({...data,episodes:[{...item,...changed}]},now));
assert.throws(() => buildStories({...data,episodes:[item,item]},now));
const two = buildStories({...data,episodes:[item,{...item,slug:'qa-older',publishedAt:'2026-10-16T18:00:00+09:00'}]},now);
assert(two.get('stories/qa-only/index.html').includes('前の作品'));
assert(two.get('stories/qa-older/index.html').includes('次の作品'));
console.log('STORIES PASS: empty output, approval/date/path gates, escaped copy, navigation, shared body. Fixtures are memory-only.');
