// Compute the existing mapped curb samples at build time, without changing
// any sampling interval, tile, curb or tactile-strip geometry.
import fs from "node:fs/promises";
import assert from "node:assert/strict";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { MeshoptDecoder } from "three/addons/libs/meshopt_decoder.module.js";
import { samplePavementProfile } from "../location/pavement-profile.mjs";

const raw = await fs.readFile(new URL("../location/susukino-detail.glb", import.meta.url));
const gltf = await new GLTFLoader().setMeshoptDecoder(MeshoptDecoder)
  .parseAsync(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength), "");
const start = performance.now();
const profile = samplePavementProfile(gltf.scene);
console.log(`Mapped pavement sampling: ${Math.round(performance.now() - start)} ms`);
const output = new URL("../location/pavement.generated.mjs", import.meta.url);
const source = "// Generated by scripts/build-route-pavement.mjs; do not edit.\nexport default " + JSON.stringify(profile) + ";\n";
if (process.argv.includes("--check")) {
  assert.equal(await fs.readFile(output, "utf8"), source, "Regenerate mapped pavement after source changes");
  console.log("PASS: precomputed pavement equals the original map sampling exactly");
} else {
  await fs.writeFile(output, source);
}
